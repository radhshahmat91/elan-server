// Builds the endpoint table of docs/api-documentation.md from the route files themselves, so the reference cannot drift from the code.
// Usage (from the server folder):  node scripts/generate-api-docs.mjs [output-file] [--check]
// --check only verifies that every route has a description in api-descriptions.mjs and writes nothing.
// With no argument the table goes to stdout. If the output file already contains the markers
//   <!-- BEGIN ENDPOINTS --> ... <!-- END ENDPOINTS -->
// only the text between them is replaced, so the hand-written parts of the document stay as they are.
// It reads source text only; it does not start the server or need a database.
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { DESCRIPTIONS } from "./api-descriptions.mjs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const routesDir = join(root, "routes");
const out = process.argv.slice(2).find((a) => !a.startsWith("--"));

const GROUP_TITLES = {
  auth: "Accounts and sessions", me: "My account", menu: "Menu", cart: "Cart and price quote", orders: "Orders", payments: "Payments", invoices: "Invoices",
  reservations: "Reservations", tables: "Tables", reviews: "Reviews", coupons: "Coupons", recommendations: "Recommendations", concierge: "Concierge (website assistant)",
  restaurant: "Restaurant profile and settings", contact: "Contact form", newsletter: "Newsletter", gallery: "Gallery", chat: "Support chat", staff: "Kitchen and delivery",
  admin: "Customers, team, roles and audit", adminMenu: "Menu management", analytics: "Analytics", content: "Website content (FAQ)", inventory: "Inventory", uploads: "Uploads", health: "Health",
};

const files = readdirSync(routesDir).filter((f) => f.endsWith(".routes.js")).sort();
const groups = [];
const undocumented = [];
const seen = new Set();

for (const file of files) {
  const src = readFileSync(join(routesDir, file), "utf8");
  const basePath = /export const basePath = ['"`]([^'"`]+)['"`]/.exec(src)?.[1];
  if (!basePath) continue;
  const key = file.replace(".routes.js", "");
  const rows = [];
  // `router.use(requireAuth)` guards every route declared after it in that file.
  const guardAt = /router\.use\(requireAuth\)/.exec(src)?.index ?? Infinity;
  const re = /router\.(get|post|put|patch|delete)\(\s*['"`]([^'"`]*)['"`]/g;
  const hits = [...src.matchAll(re)];
  hits.forEach((m, i) => {
    const chunk = src.slice(m.index, hits[i + 1]?.index ?? src.length);
    const head = chunk.split(/\n\}\);|\n\s*\}\n\);/)[0] ?? chunk;
    const perms = [...head.matchAll(/requirePermission\(([^)]*)\)/g)].map((p) => p[1].replace(/['"`\s]/g, "")).filter(Boolean);
    const roles = [...head.matchAll(/requireRole\(([^)]*)\)/g)].map((p) => p[1].replace(/['"`\s]/g, "")).filter(Boolean);
    const auth = perms.length ? `Permission: ${perms.join(", ")}` : roles.length ? `Role: ${roles.join(", ")}` : /requireAuth/.test(head) || m.index > guardAt ? "Signed in" : "Public";
    const evalMs = (expr) => expr.replace(/_/g, "").split("*").reduce((n, part) => n * Number(part.trim()), 1);
    const win = /windowMs:\s*([\d_ *]+?)\s*[,}]/.exec(head);
    const cap = /limit:\s*(\d+)/.exec(head);
    let limitText = "";
    if (win && cap) {
      const ms = evalMs(win[1]);
      limitText = `${cap[1]} per ${ms >= 60000 ? `${Math.round(ms / 60000)} min` : `${Math.round(ms / 1000)} s`}`;
    }
    // The nearest comment block directly above the route is its description.
    const before = src.slice(0, m.index).split("\n");
    const notes = [];
    for (let j = before.length - 1; j >= 0; j--) {
      const line = before[j].trim();
      if (line.startsWith("//")) {
        if (/-{4,}/.test(line)) break; // a section divider, not a description of this route
        notes.unshift(line.replace(/^\/\/\s?/, ""));
      }
      else if (line === "" && notes.length === 0) continue;
      else break;
    }
    const full = `/api${basePath}${m[2] === "/" ? "" : m[2]}`;
    const routeKey = `${m[1].toUpperCase()} ${full}`;
    const said = DESCRIPTIONS[routeKey];
    const extra = notes.join(" ");
    if (!said) undocumented.push(routeKey);
    seen.add(routeKey);
    rows.push({ method: m[1].toUpperCase(), path: full, auth, limit: limitText, note: said ?? extra });
  });
  const lead = src.startsWith("//") ? src.split("\n").filter((l) => l.startsWith("//")).slice(0, 1).map((l) => l.replace(/^\/\/\s?/, ""))[0] ?? "" : "";
  groups.push({ key, basePath, title: GROUP_TITLES[key] ?? key, lead, rows });
}

const order = Object.keys(GROUP_TITLES);
groups.sort((a, b) => order.indexOf(a.key) - order.indexOf(b.key));
const total = groups.reduce((n, g) => n + g.rows.length, 0);

const esc = (s) => s.replace(/\|/g, "\\|");
let md = `<!-- Generated by server/scripts/generate-api-docs.mjs. ${total} endpoints in ${groups.length} route files. Edit the route files, then regenerate. -->\n\n`;
for (const g of groups) {
  md += `### ${g.title}\n\nMounted at \`/api${g.basePath}\`.${g.lead && !g.lead.startsWith("import") ? ` ${esc(g.lead)}` : ""}\n\n`;
  md += "| Method | Path | Who can call it | Limit | Notes |\n|---|---|---|---|---|\n";
  for (const r of g.rows) md += `| ${r.method} | \`${r.path}\` | ${esc(r.auth)} | ${r.limit} | ${esc(r.note)} |\n`;
  md += "\n";
}
const BEGIN = "<!-- BEGIN ENDPOINTS -->";
const END = "<!-- END ENDPOINTS -->";
if (process.argv.includes("--check")) {
  // verification only: nothing is written
} else if (!out) {
  process.stdout.write(md);
} else if (existsSync(out) && readFileSync(out, "utf8").includes(BEGIN) && readFileSync(out, "utf8").includes(END)) {
  const current = readFileSync(out, "utf8");
  const head = current.slice(0, current.indexOf(BEGIN) + BEGIN.length);
  const tail = current.slice(current.indexOf(END));
  writeFileSync(out, `${head}\n\n${md.trimEnd()}\n\n${tail}`);
} else {
  writeFileSync(out, md);
}
const stale = Object.keys(DESCRIPTIONS).filter((k) => !seen.has(k));
console.error(`${total} endpoints in ${groups.length} route files`);
if (undocumented.length) console.error(`No description in scripts/api-descriptions.mjs for:\n  ${undocumented.join("\n  ")}`);
if (stale.length) console.error(`Descriptions for routes that no longer exist:\n  ${stale.join("\n  ")}`);
if (process.argv.includes("--check") && (undocumented.length || stale.length)) process.exit(1);
